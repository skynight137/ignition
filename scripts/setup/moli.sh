# shellcheck shell=bash
# Moli — a from-scratch Rust headless browser engine for AI agents
# (lexmount/moli), driven over CDP. Sourced by setup.sh.
#
# Design: one static binary, pinned by version + size + SHA256, plus
# a CDP server mode (`moli serve`) that Playwright's client library
# drives from the tour venv (scripts/tour.py --browser moli — the
# venv is the lightpanda lane's; Moli IS the browser, no browser
# download ever happens). The property that earns it a tour seat:
# SESSION PERSISTENCE — cookies and web storage live in
# partition-specific SQLite databases inside the server, so a
# logged-in session (and its Cloudflare clearance) survives server
# restarts instead of being thrown away per run. See
# references/moli.md.
#
# Layout (mirrors the lightpanda state root): everything lives under
# $XDG_CONFIG_HOME/moli (persistent, under $REPL_HOME) —
#   moli              the engine binary (symlinked into $XDG_BIN_HOME)
#   .env / cookies.json   operator config + the login jar (user data —
#                     preserved by --clean, like lightpanda's)
#   serve.log         lane/tour-created; the autostarted server's log
# The server process itself keeps its profile data under
# $XDG_DATA_HOME (Moli's own data dir) — workspace-anchored on repl,
# so sessions persist across workspace restarts.
#
# The release publishes NO checksum asset, so the SHA256 pin below
# was computed from the official release download when the pin was
# made. It moves WITH MOLI_VERSION (profile-repl.sh): bump the
# version without refreshing it and the install dies on the size
# check, loudly, by design. x86_64 only for now — that is the one
# asset verified; other arches die naming the gap rather than
# guessing an asset name.

MOLI_HOME="${MOLI_HOME:-${XDG_CONFIG_HOME:-$HOME/.config}/moli}"
MOLI_BIN="$MOLI_HOME/moli"

moli_asset_name() {
  case "$(uname -m)" in
    x86_64|amd64)   echo "moli-x86_64-unknown-linux-gnu.tar.gz" ;;
    *)              die "moli: unsupported arch $(uname -m) — only the x86_64 release asset is pinned/verified" ;;
  esac
}

# Pinned size (bytes) + SHA256 of the official $MOLI_VERSION asset.
moli_asset_size() { echo "45179259"; }
moli_asset_sha256() { echo "7e10f9a5b62371da56203b21ac0172bbe3c3626de189fc3742b91b2e2b8cdd39"; }

moli_write_env_example() {
  # A fill-in TEMPLATE for the tour config, dropped by setup next to
  # the real .env in $MOLI_HOME — refreshed on every --moli run (it
  # is a template, not user config; the real .env is never touched).
  local f="$MOLI_HOME/.env.example"
  mkdir -p "$(dirname "$f")" || return 0
  cat > "$f" <<'EOF'
# tour config — copy this file to ".env" in this same directory and
# fill in the values. Only the vars you set are used.
#
# Precedence ("big env" rule): a var already set in the system
# environment WINS; this file only fills gaps. tour.py logs at
# startup which source each var came from ("from system env (.env
# file skipped)" / "from .env file"), so a run's config is auditable,
# never silent.
#
# Template written by setup.sh --moli; safe to regenerate, never
# read by the tour itself.

# REQUIRED: the projects the tour keeps alive, comma-separated, in
# stop order. Put the tour's own host FIRST — a pilot that opens
# itself first heals itself before it tours the others.
TOUR_LINKS=https://replit.com/@you/this-project,https://replit.com/@you/other-project

# The login jar (browser-export or Playwright JSON) for the account
# that can open every project in TOUR_LINKS. The jar SEEDS the
# session at tour start; afterwards the server's own persisted
# cookies/storage (SQLite partitions) carry it — that persistence
# is the point of this engine.
# TOUR_COOKIES=/path/to/cookies.json

# Tour shape (defaults shown — the proven fleet config):
# TOUR_DWELL_S=60            seconds the tab is held per stop
# TOUR_GAP_S=0               sleep between stops, tab closed
# TOUR_MAX_EARLY_FAILURES=3  consecutive failed stops before the tour aborts (0 = never)

# Moli engine knobs:
# MOLI_CDP_URL=http://127.0.0.1:9222   the `moli serve` CDP endpoint
# TOUR_MOLI_AUTOSTART=1      1 = the tour spawns `moli serve` itself
#                            when the endpoint is down; 0 = a resident
#                            launcher (launch-moli) owns the server
EOF
  ok "moli tour config template: $f (copy to .env and fill in)"
}

moli_write_launcher() {
  # launch-moli: the resident-server entry for workflows (the
  # launch-camofox shape). It does real work the caller cannot: it
  # pins the loopback bind + the native CDP port default, so a
  # workflow task is just `launch-moli`.
  local f="$XDG_BIN_HOME/launch-moli"
  mkdir -p "$XDG_BIN_HOME" || return 0
  cat > "$f" <<'EOF'
#!/bin/sh
# launch-moli — resident Moli CDP server for the session tour.
# Generated by setup.sh --moli; regenerate with --fix or --moli.
# Bind is loopback (the tour is a local client); port is MOLI_PORT,
# default 9222 (Moli's native CDP port). Session state lives in
# Moli's data dir under $XDG_DATA_HOME — workspace-anchored on
# repl, so cookies/storage survive restarts.
exec "$(dirname "$0")/moli" serve --host 127.0.0.1 --port "${MOLI_PORT:-9222}"
EOF
  chmod +x "$f"
  ok "moli launcher: $f"
}

install_moli() {
  step "Moli browser (pinned $MOLI_VERSION)"
  need_cmd curl
  need_cmd tar
  mkdir -p "$XDG_BIN_HOME" "$MOLI_HOME"

  local asset url tmp extract
  asset="$(moli_asset_name)"
  url="$MOLI_RELEASE_BASE/v$MOLI_VERSION/$asset"
  tmp="$XDG_DATA_HOME/_moli.tar.gz"
  extract="$XDG_DATA_HOME/_moli.extract"

  # Already at the pinned version: no download, no re-verify — only
  # the template/launcher/wiring below are re-asserted. Re-running
  # an installer is the repair path, so it must stay cheap and quiet
  # (tailscale shape).
  if [[ -x "$MOLI_BIN" ]] \
     && [[ "$("$MOLI_BIN" --version 2>/dev/null || true)" == "moli $MOLI_VERSION" ]]; then
    skip "moli $MOLI_VERSION already installed ($MOLI_BIN)"
  else
    echo "  Downloading $asset"
    curl -fsSL "$url" -o "$tmp" || die "moli download failed: $url"
    # Size first (cheap corruption catch), then the pinned SHA256 —
    # upstream publishes no checksum asset, so the pin recorded in
    # this module is the reference (see the header).
    local got_size want_size
    got_size="$(stat -c%s "$tmp" 2>/dev/null || echo 0)"
    want_size="$(moli_asset_size)"
    if [[ "$got_size" != "$want_size" ]]; then
      rm -f "$tmp"
      die "moli ($asset) size mismatch (got $got_size, expected $want_size for $MOLI_VERSION) — download may be corrupt, or MOLI_VERSION moved without refreshing the pins in scripts/setup/moli.sh"
    fi
    verify_sha256 "$tmp" "$(moli_asset_sha256)" "moli ($asset)"
    rm -rf "$extract"; mkdir -p "$extract"
    tar -xzf "$tmp" -C "$extract" || die "moli: tarball extract failed: $tmp"
    local inner="$extract/moli-v$MOLI_VERSION-x86_64-unknown-linux-gnu/moli"
    [[ -x "$inner" ]] || die "moli: binary not found at expected tarball path ($inner) — release layout changed?"
    chmod +x "$inner"
    _bin_replace_note "$MOLI_BIN"
    rm -f "$MOLI_BIN"
    mv -f "$inner" "$MOLI_BIN"
    rm -rf "$extract"; rm -f "$tmp"
    # The binary must actually run on this box. NOTE: the probe is
    # the `--version` FLAG — `moli version` is not a subcommand.
    local ver; ver="$("$MOLI_BIN" --version 2>/dev/null || true)"
    [[ "$ver" == "moli $MOLI_VERSION" ]] \
      || die "moli binary does not run as $MOLI_VERSION (got '${ver:-nothing}') — wrong arch or a corrupt install"
    ok "moli installed: $MOLI_BIN ($ver)"
  fi

  # PATH entry: a symlink in the single bin dir, the real file stays
  # in the tool's home (the lightpanda state-root shape).
  ln -sfn "$MOLI_BIN" "$XDG_BIN_HOME/moli"

  moli_write_launcher
  moli_write_env_example

  record_tool_env_vars MOLI_HOME MOLI_BIN
  record_tool_path_dirs "$XDG_BIN_HOME"
  wire_tool moli MOLI_HOME MOLI_BIN -- "$XDG_BIN_HOME"

  ok "moli ready — tour: bash $SCRIPTS_DIR/tour.sh --browser moli --machine repl (config: $MOLI_HOME/.env, see .env.example there; preflight: tour.sh --check; the tour venv is the lightpanda lane's)"
}

clean_moli() {
  if ! _present "$MOLI_BIN" "$XDG_BIN_HOME/moli" "$XDG_BIN_HOME/launch-moli"; then
    nothing_removed "Moli"; return 0
  fi
  step "Removing Moli browser"
  rm -f "$XDG_BIN_HOME/moli" "$XDG_BIN_HOME/launch-moli"
  rm -f "$MOLI_BIN"
  rm -f "$MOLI_HOME/serve.log"
  # Operator data (.env config + the cookie jar login) is user data —
  # kept; delete $MOLI_HOME to wipe it. The server's own profile
  # data under $XDG_DATA_HOME is Moli's — also kept.
  ok "Moli removed (binary + launcher; config + cookie jar kept in $MOLI_HOME)"
}
